create table if not exists public.messyiq_retail_orders (
  id bigint generated by default as identity primary key,
  synthetic_order_ref text not null unique,
  product_group text not null,
  region text not null,
  order_status text not null check (order_status in ('Processing', 'Fulfilled', 'Returned', 'Cancelled')),
  period_year integer not null,
  order_value numeric(10,2) not null check (order_value >= 0),
  review_signal text not null check (review_signal in ('none', 'delivery_delay', 'refund_requested', 'payment_follow_up')),
  documented_reason text
);

create table if not exists public.messyiq_workforce_engagements (
  id bigint generated by default as identity primary key,
  synthetic_engagement_ref text not null unique,
  department text not null,
  engagement_status text not null check (engagement_status in ('Active', 'On Leave', 'Completed', 'Exited')),
  period_year integer not null,
  review_signal text not null check (review_signal in ('none', 'support_requested', 'schedule_change', 'exit_follow_up')),
  documented_reason text
);

create table if not exists public.messyiq_operations_work_orders (
  id bigint generated by default as identity primary key,
  synthetic_work_order_ref text not null unique,
  facility text not null,
  issue_type text not null,
  priority text not null check (priority in ('Routine', 'Planned', 'Urgent')),
  work_order_status text not null check (work_order_status in ('Open', 'In Progress', 'Resolved', 'Closed')),
  period_year integer not null,
  review_signal text not null check (review_signal in ('none', 'safety_review', 'parts_delay', 'inspection_due')),
  documented_reason text
);

create index if not exists messyiq_retail_period_idx on public.messyiq_retail_orders(period_year);
create index if not exists messyiq_workforce_period_idx on public.messyiq_workforce_engagements(period_year);
create index if not exists messyiq_operations_period_idx on public.messyiq_operations_work_orders(period_year);

alter table public.messyiq_retail_orders enable row level security;
alter table public.messyiq_workforce_engagements enable row level security;
alter table public.messyiq_operations_work_orders enable row level security;

drop policy if exists "MessyIQ demo retail rows are read-only" on public.messyiq_retail_orders;
drop policy if exists "MessyIQ demo workforce rows are read-only" on public.messyiq_workforce_engagements;
drop policy if exists "MessyIQ demo operations rows are read-only" on public.messyiq_operations_work_orders;

create policy "MessyIQ demo retail rows are read-only"
  on public.messyiq_retail_orders for select to authenticated using (true);
create policy "MessyIQ demo workforce rows are read-only"
  on public.messyiq_workforce_engagements for select to authenticated using (true);
create policy "MessyIQ demo operations rows are read-only"
  on public.messyiq_operations_work_orders for select to authenticated using (true);

grant select on public.messyiq_retail_orders to authenticated;
grant select on public.messyiq_workforce_engagements to authenticated;
grant select on public.messyiq_operations_work_orders to authenticated;

do $$
declare
  i integer;
  product_groups text[] := array['Books', 'Home', 'Clothing', 'Electronics', 'Food'];
  regions text[] := array['North', 'Central', 'South', 'West'];
  departments text[] := array['Operations', 'Customer Care', 'Technology', 'Finance', 'Facilities'];
  facilities text[] := array['North Campus', 'Central Hub', 'West Depot', 'South Office'];
  issues text[] := array['Preventive maintenance', 'Equipment repair', 'Safety inspection', 'Supply replacement'];
  retail_status text;
  workforce_status text;
  operations_status text;
  retail_signal text;
  workforce_signal text;
  operations_signal text;
  note text;
begin
  for i in 1..45 loop
    retail_status := (array['Processing', 'Fulfilled', 'Returned', 'Cancelled'])[((i - 1) % 4) + 1];
    retail_signal := case when i % 9 = 0 then 'delivery_delay'
                          when i % 11 = 0 then 'refund_requested'
                          when i % 13 = 0 then 'payment_follow_up'
                          else 'none' end;
    note := case retail_signal when 'delivery_delay' then 'Carrier delay recorded'
                               when 'refund_requested' then 'Refund request recorded'
                               when 'payment_follow_up' then 'Payment follow-up recorded'
                               else null end;
    insert into public.messyiq_retail_orders
      (synthetic_order_ref, product_group, region, order_status, period_year, order_value, review_signal, documented_reason)
    values
      ('DEMO-ORD-' || lpad(i::text, 4, '0'),
       product_groups[((i - 1) % array_length(product_groups, 1)) + 1],
       regions[((i - 1) % array_length(regions, 1)) + 1],
       retail_status, 2024 + (i % 3), (19 + ((i * 37) % 480))::numeric(10,2),
       retail_signal, note)
    on conflict (synthetic_order_ref) do nothing;

    workforce_status := (array['Active', 'On Leave', 'Completed', 'Exited'])[((i - 1) % 4) + 1];
    workforce_signal := case when workforce_status = 'On Leave' then 'support_requested'
                             when workforce_status = 'Exited' then 'exit_follow_up'
                             when i % 10 = 0 then 'schedule_change'
                             else 'none' end;
    note := case workforce_status when 'On Leave' then 'Leave request recorded for human review'
                                  when 'Exited' then (array['Contract ended', 'Role transition recorded', 'Personal departure recorded'])[((i - 1) % 3) + 1]
                                  else null end;
    insert into public.messyiq_workforce_engagements
      (synthetic_engagement_ref, department, engagement_status, period_year, review_signal, documented_reason)
    values
      ('DEMO-WRK-' || lpad(i::text, 4, '0'),
       departments[((i - 1) % array_length(departments, 1)) + 1],
       workforce_status, 2024 + (i % 3), workforce_signal, note)
    on conflict (synthetic_engagement_ref) do nothing;

    operations_status := (array['Open', 'In Progress', 'Resolved', 'Closed'])[((i - 1) % 4) + 1];
    operations_signal := case when i % 12 = 0 then 'safety_review'
                              when i % 7 = 0 then 'parts_delay'
                              when i % 10 = 0 then 'inspection_due'
                              else 'none' end;
    note := case operations_signal when 'safety_review' then 'Safety inspection requested'
                                   when 'parts_delay' then 'Replacement parts delayed'
                                   when 'inspection_due' then 'Scheduled inspection due'
                                   else null end;
    insert into public.messyiq_operations_work_orders
      (synthetic_work_order_ref, facility, issue_type, priority, work_order_status, period_year, review_signal, documented_reason)
    values
      ('DEMO-OPS-' || lpad(i::text, 4, '0'),
       facilities[((i - 1) % array_length(facilities, 1)) + 1],
       issues[((i - 1) % array_length(issues, 1)) + 1],
       case when i % 12 = 0 then 'Urgent' when i % 3 = 0 then 'Planned' else 'Routine' end,
       operations_status, 2024 + (i % 3), operations_signal, note)
    on conflict (synthetic_work_order_ref) do nothing;
  end loop;
end $$;

create or replace view public.messyiq_demo_records
with (security_invoker = true)
as
  select
    'retail'::text as domain,
    synthetic_order_ref as record_ref,
    product_group as segment,
    order_status as status,
    period_year,
    order_value as metric_value,
    review_signal,
    documented_reason
  from public.messyiq_retail_orders
  union all
  select
    'workforce'::text as domain,
    synthetic_engagement_ref as record_ref,
    department as segment,
    engagement_status as status,
    period_year,
    null::numeric as metric_value,
    review_signal,
    documented_reason
  from public.messyiq_workforce_engagements
  union all
  select
    'operations'::text as domain,
    synthetic_work_order_ref as record_ref,
    facility as segment,
    work_order_status as status,
    period_year,
    null::numeric as metric_value,
    review_signal,
    documented_reason
  from public.messyiq_operations_work_orders;

grant select on public.messyiq_demo_records to authenticated;
