create table if not exists public.education_students (
  id bigint generated by default as identity primary key,
  student_code text not null unique,
  full_name text not null,
  date_of_birth date not null,
  gender text not null check (gender in ('Female', 'Male', 'Non-binary')),
  program text not null,
  cohort integer not null,
  admission_year integer not null,
  campus text not null,
  guardian_name text not null,
  guardian_phone text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.education_academic_events (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.education_students(id) on delete cascade,
  academic_year integer not null,
  academic_term text not null check (academic_term in ('Term 1', 'Term 2', 'Term 3')),
  status text not null check (status in ('Admitted', 'Enrolled', 'Promoted', 'Graduated', 'On Leave', 'Withdrew', 'Transfer Out')),
  year_of_study integer not null check (year_of_study between 1 and 6),
  gpa numeric(3,2) check (gpa between 0 and 4),
  attendance_percent numeric(5,2) check (attendance_percent between 0 and 100),
  fee_status text not null check (fee_status in ('Paid', 'Partial', 'Unpaid')),
  reason text,
  event_date date not null
);

create index if not exists education_events_student_idx on public.education_academic_events(student_id);
create index if not exists education_events_year_idx on public.education_academic_events(academic_year);
create index if not exists education_events_status_idx on public.education_academic_events(status);

alter table public.education_students enable row level security;
alter table public.education_academic_events enable row level security;

drop policy if exists "Education tables are read-only to analysts" on public.education_students;
drop policy if exists "Education events are read-only to analysts" on public.education_academic_events;

create policy "Education tables are read-only to analysts"
  on public.education_students for select
  to authenticated
  using (true);

create policy "Education events are read-only to analysts"
  on public.education_academic_events for select
  to authenticated
  using (true);

